// Helper: derive type tag from category
export function deriveTypeTag(category: string): CreativeTypeTag {
  const map: Record<string, CreativeTypeTag> = {
    "Display": "Display",
    "Video": "Vídeo",
    "Native": "Texto",
    "Social": "Social",
    "Audio": "Áudio",
    "Stories/Reels": "Vídeo",
    "Carousel": "Social",
    "Push": "Push",
  };
  return map[category] || "Display";
}

// Helper functions
export function isSpecActive(spec: CreativeSpecDefinition): boolean {
  return spec.active !== false;
}

export function getSpecsByPlatform(platform: string): CreativeSpecDefinition[] {
  return CREATIVE_SPECS_DATABASE.filter((spec) => spec.platform === platform);
}

export function getActiveSpecsByPlatform(platform: string): CreativeSpecDefinition[] {
  return CREATIVE_SPECS_DATABASE.filter((spec) => spec.platform === platform && isSpecActive(spec));
}

export function getSpecsByCategory(category: string): CreativeSpecDefinition[] {
  return CREATIVE_SPECS_DATABASE.filter((spec) => spec.category === category);
}

export function getSpecsByPlatformAndCategory(
  platform: string,
  category: string
): CreativeSpecDefinition[] {
  return CREATIVE_SPECS_DATABASE.filter(
    (spec) => spec.platform === platform && spec.category === category
  );
}

export function getPublishersByPlatform(platform: string): string[] {
  const specs = getSpecsByPlatform(platform);
  const publishers = specs.map((s) => s.publisher).filter(Boolean) as string[];
  return [...new Set(publishers)];
}

export function getUniquePlatforms(): string[] {
  return [...new Set(CREATIVE_SPECS_DATABASE.map((spec) => spec.platform))];
}

export function getUniqueCategories(): string[] {
  return [...new Set(CREATIVE_SPECS_DATABASE.map((spec) => spec.category))];
}

export function getCategoriesByPlatform(platform: string): string[] {
  const specs = getSpecsByPlatform(platform);
  return [...new Set(specs.map((spec) => spec.category))];
}

export function getSpecsByPlatformPublisherCategory(
  platform: string,
  publisher: string | undefined,
  category: string
): CreativeSpecDefinition[] {
  return CREATIVE_SPECS_DATABASE.filter(
    (spec) =>
      spec.platform === platform &&
      spec.category === category &&
      (publisher ? spec.publisher === publisher : !spec.publisher)
  );
}
